<?php

namespace App\Jobs;

use App\Models\ChapterImport;
use App\Models\EditionChapter;
use App\Services\Content\ChapterRevisionImporter;
use App\Services\Content\ChapterUpload;
use App\Services\Content\PrivateImages;
use Illuminate\Contracts\Queue\ShouldQueue;
use Illuminate\Foundation\Queue\Queueable;
use Illuminate\Http\Request;
use Illuminate\Http\UploadedFile;
use Illuminate\Support\Facades\Log;
use Illuminate\Support\Facades\Storage;
use Illuminate\Validation\ValidationException;

/** A database-backed job. Staged bytes never enter the serialized job payload. */
class ProcessChapterImport implements ShouldQueue
{
    use Queueable;

    public int $timeout = 600;
    public int $tries = 1;

    public function __construct(public readonly string $importId) {}

    public function handle(ChapterUpload $uploads, PrivateImages $images, ChapterRevisionImporter $writer): void
    {
        $import = ChapterImport::query()->findOrFail($this->importId);
        if ($import->status === 'completed' || $import->status === 'failed') return;
        $disk = Storage::disk(PrivateImages::DISK);
        $import->update(['status' => 'processing', 'started_at' => now()]);
        try {
            $chapter = EditionChapter::query()->findOrFail($import->edition_chapter_id);
            abort_unless($chapter->series_id === $import->series_id, 404);
            $files = [];
            foreach ($import->files as $item) {
                $stored = $item['key'];
                // Stored keys were generated by the server; never use submitted paths.
                if (! is_string($stored) || ! str_starts_with($stored, $import->staging_prefix.'/') || ! $disk->exists($stored)) {
                    throw new \RuntimeException('Staged upload missing.');
                }
                $files[] = new UploadedFile($disk->path($stored), $item['name'], null, null, true);
            }
            $request = Request::create('/', 'POST');
            if (count($files) === 1 && ! $import->files[0]['is_image_batch']) {
                $request->files->set('upload', $files[0]);
            } else {
                $request->files->set('images', $files);
            }
            $prepared = $uploads->prepare($request, $import->archive_only);
            $result = $writer->persist($chapter, $prepared, $images, (int) $import->actor_id, $import->request_key);
            $import->update([
                'status' => 'completed', 'revision_id' => $result['revision']->id,
                'finished_at' => now(), 'error_message' => null,
            ]);
        } catch (\Throwable $e) {
            Log::warning('Manga async chapter import failed', ['import_id' => $import->id, 'exception' => $e]);
            $message = $e instanceof ValidationException
                ? implode(' ', $e->errors()['upload'] ?? ['ملف الفصل غير صالح.'])
                : 'تعذرت معالجة الفصل. راجع سجل Laravel وحاول مجددًا بطلب جديد.';
            $import->update(['status' => 'failed', 'error_message' => mb_substr($message, 0, 500), 'finished_at' => now()]);
        } finally {
            $disk->deleteDirectory($import->staging_prefix);
        }
    }
    /** Queue-level failures (including timeouts) still leave a visible admin status. */
    public function failed(?\Throwable $exception): void
    {
        $import = ChapterImport::query()->find($this->importId);
        if ($import !== null && ! in_array($import->status, ['completed', 'failed'], true)) {
            $import->update([
                'status' => 'failed',
                'error_message' => 'انقطعت مهمة معالجة الفصل. حاول الرفع مرة أخرى بمفتاح جديد.',
                'finished_at' => now(),
            ]);
            Storage::disk(PrivateImages::DISK)->deleteDirectory($import->staging_prefix);
        }
    }
}
